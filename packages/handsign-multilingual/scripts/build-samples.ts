// Builds the ready-made samples of handsign-multilingual/samples from the datasets of data/: the features of each
// hand (HandSignClassifier.features), one byte per value, in base64. Run it again when the features or the data change.
//
//   pnpm build:samples
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { HandSignClassifier } from '../src'
import {
  type Dataset,
  loadDataset,
  mergeDatasets,
  toHand
} from '../tests/evaluation'

/** One byte per value: from -127/SCALE to 127/SCALE (the features of ASLNow! go from -2.31 to 2.31) */
const SCALE = 40

type Source = { name: string; output: string; datasets: Dataset[] }

function build({ name, output, datasets }: Source) {
  const dataset = datasets.length === 1 ? datasets[0] : mergeDatasets(datasets)
  const samples = dataset.samples.map((sample) => ({
    letter: sample.letter,
    features: HandSignClassifier.features(toHand(sample, dataset))
  }))
  // In order of letter: each letter and how many it has
  samples.sort((a, b) => a.letter.localeCompare(b.letter, 'es'))
  const dimensions = samples[0].features.length
  const bytes = new Int8Array(samples.length * dimensions)
  samples.forEach(({ features }, i) => {
    features.forEach((value, d) => {
      bytes[i * dimensions + d] = Math.max(
        -127,
        Math.min(127, Math.round(value * SCALE))
      )
    })
  })
  const letters: Array<[string, number]> = []
  for (const { letter } of samples) {
    const last = letters[letters.length - 1]
    if (last?.[0] === letter) last[1]++
    else letters.push([letter, 1])
  }
  const packed = {
    source: dataset.source,
    revision: (dataset as { revision?: string }).revision,
    license: dataset.license,
    language: dataset.language,
    scale: SCALE,
    dimensions,
    letters,
    data: Buffer.from(bytes.buffer).toString('base64')
  }
  writeFileSync(
    new URL(`../src/samples/${output}.ts`, import.meta.url),
    `// Generated by scripts/build-samples.ts from data/ (see data/README.md and LICENSE): do not edit\n` +
      `export const ${name} = ${JSON.stringify(packed, null, 2)} as const\n`
  )
  console.log(
    `${output}: ${samples.length} samples of ${letters.length} letters, ${bytes.length} bytes (${packed.data.length} in base64)`
  )
}

const data = new URL('../data/', import.meta.url)
build({
  name: 'ASL_NOW',
  output: 'asl-now',
  datasets: [loadDataset(new URL('asl-now.json', data))]
})

// The Spanish alphabet, from the recordings of the demo (data/recordings/ssl-<person>.json)
const recordings = new URL('recordings/', data)
const spanish = existsSync(recordings)
  ? readdirSync(recordings)
      .filter((file) => /^ssl-.+\.json$/.test(file))
      .map((file) => loadDataset(new URL(file, recordings)))
  : []
if (spanish.length > 0) build({ name: 'LSE', output: 'lse', datasets: spanish })
else
  console.log(
    'lse: there are no recordings of the Spanish alphabet yet (data/recordings/ssl-*.json)'
  )
